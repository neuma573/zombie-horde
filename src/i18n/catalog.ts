export type MessageKey = keyof typeof korean;
export type Locale = 'en' | 'ko';

export function translate(locale: Locale, message: string, values: Record<string, string | number> = {}): string {
  const template = locale === 'ko' ? korean[message as MessageKey] ?? message : message;
  return template.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder));
}
